-- study ユーザーで FREEPDB1 に接続して実行する。
SET LINESIZE 200
SET PAGESIZE 200
SET SERVEROUTPUT OFF
SET FEEDBACK OFF
COLUMN plan_table_output FORMAT A200

PROMPT ===== (A) INDEX UNIQUE SCAN: 主キーで 1 行 =====
SELECT /*+ GATHER_PLAN_STATISTICS */ order_date, amount FROM orders WHERE order_id = 12345;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

PROMPT ===== (B) INDEX RANGE SCAN: 特定の日の受注 =====
SELECT /*+ GATHER_PLAN_STATISTICS */ COUNT(amount) FROM orders WHERE order_date = DATE '2024-03-01';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

PROMPT ===== (C) TABLE ACCESS FULL: 金額で絞る（索引なし） =====
SELECT /*+ GATHER_PLAN_STATISTICS */ COUNT(*) FROM orders WHERE amount > 49000;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

PROMPT ===== (D) INDEX FAST FULL SCAN: 索引の列だけで答えが出る =====
SELECT /*+ GATHER_PLAN_STATISTICS */ COUNT(DISTINCT customer_id) FROM orders;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

PROMPT ===== (E) INDEX FULL SCAN (MIN/MAX): 最大値だけ取る =====
SELECT /*+ GATHER_PLAN_STATISTICS */ MAX(order_date) FROM orders;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

PROMPT ===== (F1) SHIPPED を FULL で読む（オプティマイザに任せる） =====
SELECT /*+ GATHER_PLAN_STATISTICS */ SUM(amount) FROM orders WHERE status = 'SHIPPED';
