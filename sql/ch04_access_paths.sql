PROMPT ===== (F2) SHIPPED を索引で読む（ヒントで強制） =====
SELECT /*+ GATHER_PLAN_STATISTICS INDEX(orders orders_status_ix) */ SUM(amount) FROM orders WHERE status = 'SHIPPED';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

