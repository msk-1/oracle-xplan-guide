PROMPT ===== クラスタリング・ファクタと表のブロック数 =====
COLUMN index_name FORMAT A20
SELECT index_name, clustering_factor, num_rows, leaf_blocks
FROM   user_indexes WHERE table_name = 'ORDERS' ORDER BY clustering_factor;
SELECT blocks, num_rows FROM user_tables WHERE table_name = 'ORDERS';

PROMPT ===== (B2) INDEX RANGE SCAN + 表アクセス: 特定の日の金額合計 =====
SELECT /*+ GATHER_PLAN_STATISTICS */ SUM(amount) FROM orders WHERE order_date = DATE '2024-03-01';
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

PROMPT ===== 同じ日付の行が入っているブロック =====
SELECT order_id, DBMS_ROWID.ROWID_BLOCK_NUMBER(rowid) AS block_no
FROM   orders
WHERE  order_date = DATE '2024-03-01'
ORDER  BY order_id
FETCH  FIRST 5 ROWS ONLY;

SELECT COUNT(DISTINCT DBMS_ROWID.ROWID_BLOCK_NUMBER(rowid)) AS blocks, COUNT(*) AS cnt
FROM   orders
WHERE  order_date = DATE '2024-03-01';

PROMPT ===== 連続する受注番号 200 件が入っているブロック =====
SELECT COUNT(DISTINCT DBMS_ROWID.ROWID_BLOCK_NUMBER(rowid)) AS blocks, COUNT(*) AS cnt
FROM   orders
WHERE  order_id BETWEEN 12345 AND 12544;

SELECT /*+ GATHER_PLAN_STATISTICS INDEX(orders) */ SUM(amount)
FROM   orders
WHERE  order_id BETWEEN 12345 AND 12544;
SELECT * FROM TABLE(DBMS_XPLAN.DISPLAY_CURSOR(NULL, NULL, 'ALLSTATS LAST'));

PROMPT ===== 索引で見つけた行を表で捨てている例 =====
SELECT /*+ GATHER_PLAN_STATISTICS INDEX(orders orders_date_ix) */ SUM(amount) FROM orders
WHERE order_date BETWEEN DATE '2024-03-01' AND DATE '2024-03-02' AND amount > 49000;
